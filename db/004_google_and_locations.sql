-- Short-lived single-use codes: the API redirects back to the web/mobile app with one of these after Google approves,
-- and the app swaps it for a normal session. Tokens never travel in URLs.
CREATE TABLE IF NOT EXISTS oauth_codes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  code_hash text UNIQUE NOT NULL,
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL,
  consumed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS oauth_codes_expiry ON oauth_codes (expires_at);

